<#
.SYNOPSIS
    Install 7-Zip via Tanium Deploy

.DESCRIPTION
    This script installs 7-Zip version 25.01

    Product ID: 7zip.7zip
    Package ID: 7zip.7zip
    Installer Type: exe
    Generated by Get-WinGetPackage.ps1
#>

[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'

# Set up logging
$LogPath = Join-Path $env:TEMP "Install-7zip.7zip.log"
Start-Transcript -Path $LogPath -Append

try {
    Write-Host "Installing 7-Zip 25.01..."
    Write-Host "Product ID: 7zip.7zip"
    Write-Host "Installer Type: exe"

    # Get the installer file path
    $InstallerPath = Join-Path $PSScriptRoot "7-Zip_25.01_Machine_X64_exe_en-US.exe"

    if (-not (Test-Path $InstallerPath)) {
        throw "Installer file not found: $InstallerPath"
    }

    Write-Host "Installer file: $InstallerPath"
    Write-Host "File size: $((Get-Item $InstallerPath).Length / 1MB) MB"
    # Execute installation
    Write-Host "Running: "$InstallerPath" /S /silent /quiet"
    $Process = Start-Process -FilePath '"$InstallerPath"' -ArgumentList '/S /silent /quiet' -Wait -PassThru -NoNewWindow
    $ExitCode = $Process.ExitCode
    Write-Host "Installation completed with exit code: $ExitCode"

    # Success codes
    $SuccessCodes = @(0)

    if ($ExitCode -in $SuccessCodes) {
        Write-Host "Installation successful!"

        if ($ExitCode -eq 3010 -or $ExitCode -eq 1641) {
            Write-Warning "A restart is required to complete the installation."
        }

        Stop-Transcript
        exit 0
    }
    else {
        throw "Installation failed with exit code: $ExitCode"
    }
}
catch {
    Write-Error "Installation failed: $_"
    Stop-Transcript
    exit 1
}
