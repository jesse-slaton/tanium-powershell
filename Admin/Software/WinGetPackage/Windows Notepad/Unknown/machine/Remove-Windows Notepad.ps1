<#
.SYNOPSIS
    Remove Windows Notepad via Tanium Deploy

.DESCRIPTION
    This script uninstalls the MSIX/AppX package: Windows Notepad
    Package ID: 9MSMLRH6LZF3
    Scope: machine

.NOTES
    Generated by Get-WinGetPackage.ps1
#>

[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'

# Set up logging
$LogPath = Join-Path $env:TEMP "Remove-9MSMLRH6LZF3.log"
Start-Transcript -Path $LogPath -Append

try {
    Write-Host "Removing Windows Notepad..."
    Write-Host "Package ID: 9MSMLRH6LZF3"
    Write-Host "Scope: machine"

    # Find installed package    $InstalledPackage = Get-AppxPackage -Name "*9MSMLRH6LZF3*" -ErrorAction SilentlyContinue
    if (-not $InstalledPackage) {
        Write-Host "Package not found - may already be uninstalled"
        Stop-Transcript
        exit 0
    }

    Write-Host "Found: $($InstalledPackage.PackageFullName)"
    Write-Host "Version: $($InstalledPackage.Version)"

    # Remove the package    # Machine scope: Remove provisioned package
    Write-Host "Removing provisioned package..."
    try {
        Remove-AppxProvisionedPackage -Online -PackageName $InstalledPackage.PackageFullName -ErrorAction SilentlyContinue | Out-Null
    }
    catch {
        Write-Warning "Could not remove provisioned package: "
    }
    # Remove user package
    Write-Host "Removing installed package..."
    Remove-AppxPackage -Package $InstalledPackage.PackageFullName
    $ExitCode = $LASTEXITCODE

    if ($null -eq $ExitCode) { $ExitCode = 0 }

    Write-Host "Removal completed with exit code: $ExitCode"

    # Success codes
    $SuccessCodes = @(0)

    if ($ExitCode -in $SuccessCodes) {
        Write-Host "Removal successful!"
        Stop-Transcript
        exit 0
    }
    else {
        throw "Removal failed with exit code: $ExitCode"
    }
}
catch {
    Write-Error "Removal failed: $_"
    Stop-Transcript
    exit 1
}
