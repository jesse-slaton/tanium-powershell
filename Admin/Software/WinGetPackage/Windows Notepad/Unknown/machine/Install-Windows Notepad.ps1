<#
.SYNOPSIS
    Install Windows Notepad via Tanium Deploy

.DESCRIPTION
    This script installs the MSIX/AppX package: Windows Notepad
    Package ID: 9MSMLRH6LZF3
    Scope: machine
    Type: Microsoft Store Package

.NOTES
    Generated by Get-WinGetPackage.ps1
    MSIX packages use PackageFamilyName for detection, not registry keys
#>

[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'

# Set up logging
$LogPath = Join-Path $env:TEMP "Install-9MSMLRH6LZF3.log"
Start-Transcript -Path $LogPath -Append

try {
    Write-Host "Installing Windows Notepad..."
    Write-Host "Package ID: 9MSMLRH6LZF3"
    Write-Host "Scope: machine"
    Write-Host "Installer Type: MSIX/AppX"
    # Get the main package file path
    $PackagePath = Join-Path $PSScriptRoot "Microsoft.WindowsNotepad_11.2507.26.0_Desktop_X64.msixbundle"

    if (-not (Test-Path $PackagePath)) {
        throw "Package file not found: $PackagePath"
    }

    Write-Host "
Main package file: $PackagePath"
    Write-Host "File size: $((Get-Item $PackagePath).Length / 1MB) MB"

    # Check if package is already installed
    $InstalledPackage = Get-AppxPackage -Name "*9MSMLRH6LZF3*" -ErrorAction SilentlyContinue

    if ($InstalledPackage) {
        Write-Host "Package already installed: $($InstalledPackage.PackageFullName)"
        Write-Host "Version: $($InstalledPackage.Version)"
        Write-Host "Installation is idempotent - skipping reinstall"
        Stop-Transcript
        exit 0
    }

    # Install the main package
    Write-Host "
Installing main package..."    # Machine scope: Use Add-AppxProvisionedPackage for system-wide installation
    Add-AppxProvisionedPackage -Online -PackagePath $PackagePath -SkipLicense
    $ExitCode = $LASTEXITCODE
    if ($null -eq $ExitCode) { $ExitCode = 0 }

    Write-Host "Installation completed with exit code: $ExitCode"

    # Success codes
    $SuccessCodes = @(0)

    if ($ExitCode -in $SuccessCodes) {
        Write-Host "Installation successful!"
        Stop-Transcript
        exit 0
    }
    else {
        throw "Installation failed with exit code: $ExitCode"
    }
}
catch {
    Write-Error "Installation failed: $_"
    Stop-Transcript
    exit 1
}
