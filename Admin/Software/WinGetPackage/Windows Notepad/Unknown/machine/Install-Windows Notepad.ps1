<#
.SYNOPSIS
    Install Windows Notepad via Tanium Deploy

.DESCRIPTION
    This script installs Windows Notepad version Unknown

    Product ID: 9MSMLRH6LZF3
    Package ID: 9MSMLRH6LZF3
    Installer Type: exe
    Generated by Get-WinGetPackage.ps1
#>

[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'

# Set up logging
$LogPath = Join-Path $env:TEMP "Install-9MSMLRH6LZF3.log"
Start-Transcript -Path $LogPath -Append

try {
    Write-Host "Installing Windows Notepad Unknown..."
    Write-Host "Product ID: 9MSMLRH6LZF3"
    Write-Host "Installer Type: exe"
    throw "No installer file found in package. This package must be rebuilt with -DownloadInstallers flag or Tanium Server must download the installer first."
    Write-Host "Installation completed with exit code: $ExitCode"

    # Success codes
    $SuccessCodes = @(0)

    if ($ExitCode -in $SuccessCodes) {
        Write-Host "Installation successful!"

        if ($ExitCode -eq 3010 -or $ExitCode -eq 1641) {
            Write-Warning "A restart is required to complete the installation."
        }

        Stop-Transcript
        exit 0
    }
    else {
        throw "Installation failed with exit code: $ExitCode"
    }
}
catch {
    Write-Error "Installation failed: $_"
    Stop-Transcript
    exit 1
}
