function New-MsixInstallScript {
    <#
    .SYNOPSIS
        Generates install script for MSIX/AppX packages (Microsoft Store apps).

    .DESCRIPTION
        Creates PowerShell install scripts for msstore packages with proper
        Add-AppxPackage commands, dependency handling, and idempotency.

    .PARAMETER PackageName
        Display name of the main package

    .PARAMETER PackageId
        Package ID (Store Product ID)

    .PARAMETER MainPackageFile
        Main package installer file (*.msix, *.msixbundle, *.appx, *.appxbundle)

    .PARAMETER DependencyFiles
        Array of dependency package files

    .PARAMETER Scope
        Installation scope (user or machine)

    .PARAMETER AllInOne
        If true, includes dependencies in the same script. If false, main package only.

    .EXAMPLE
        New-MsixInstallScript -PackageName "Windows Notepad" -PackageId "9MSMLRH6LZF3" `
            -MainPackageFile "WindowsNotepad.msixbundle" -Scope "user" -AllInOne $true

    .OUTPUTS
        String containing the PowerShell install script
    #>
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]
        [string]$PackageName,

        [Parameter(Mandatory)]
        [string]$PackageId,

        [Parameter(Mandatory)]
        [string]$MainPackageFile,

        [Parameter()]
        [string[]]$DependencyFiles = @(),

        [Parameter()]
        [ValidateSet('user', 'machine')]
        [string]$Scope = 'user',

        [Parameter()]
        [bool]$AllInOne = $true
    )

    $sanitizedName = $PackageName -replace '[\\/:*?"<>|]', '_'
    $logBaseName = $PackageId -replace '[\\/:*?"<>|]', '_'

    $script = @"
<#
.SYNOPSIS
    Install $PackageName via Tanium Deploy

.DESCRIPTION
    This script installs the MSIX/AppX package: $PackageName
    Package ID: $PackageId
    Scope: $Scope
    Type: Microsoft Store Package

.NOTES
    Generated by Get-WinGetPackage.ps1
    MSIX packages use PackageFamilyName for detection, not registry keys
#>

[CmdletBinding()]
param()

`$ErrorActionPreference = 'Stop'

# Set up logging
`$LogPath = Join-Path `$env:TEMP "Install-$logBaseName.log"
Start-Transcript -Path `$LogPath -Append

try {
    Write-Host "Installing $PackageName..."
    Write-Host "Package ID: $PackageId"
    Write-Host "Scope: $Scope"
    Write-Host "Installer Type: MSIX/AppX"

"@

    if ($AllInOne -and $DependencyFiles.Count -gt 0) {
        $script += @"
    # Install dependencies first
    Write-Host "`nInstalling $($DependencyFiles.Count) dependencies..."

"@
        foreach ($depFile in $DependencyFiles) {
            $script += @"
    `$DepPath = Join-Path `$PSScriptRoot "$depFile"
    if (Test-Path `$DepPath) {
        Write-Host "  Installing dependency: $depFile"
        try {
"@
            if ($Scope -eq 'machine') {
                $script += @"
            Add-AppxProvisionedPackage -Online -PackagePath `$DepPath -SkipLicense -ErrorAction SilentlyContinue | Out-Null
"@
            } else {
                $script += @"
            Add-AppxPackage -Path `$DepPath -ErrorAction SilentlyContinue | Out-Null
"@
            }
            $script += @"
        }
        catch {
            Write-Warning "Dependency may already be installed: $_"
        }
    }

"@
        }
    }

    $script += @"
    # Get the main package file path
    `$PackagePath = Join-Path `$PSScriptRoot "$MainPackageFile"

    if (-not (Test-Path `$PackagePath)) {
        throw "Package file not found: `$PackagePath"
    }

    Write-Host "`nMain package file: `$PackagePath"
    Write-Host "File size: `$((Get-Item `$PackagePath).Length / 1MB) MB"

    # Check if package is already installed
    `$InstalledPackage = Get-AppxPackage -Name "*$PackageId*" -ErrorAction SilentlyContinue

    if (`$InstalledPackage) {
        Write-Host "Package already installed: `$(`$InstalledPackage.PackageFullName)"
        Write-Host "Version: `$(`$InstalledPackage.Version)"
        Write-Host "Installation is idempotent - skipping reinstall"
        Stop-Transcript
        exit 0
    }

    # Install the main package
    Write-Host "`nInstalling main package..."
"@

    if ($Scope -eq 'machine') {
        $script += @"
    # Machine scope: Use Add-AppxProvisionedPackage for system-wide installation
    Add-AppxProvisionedPackage -Online -PackagePath `$PackagePath -SkipLicense
    `$ExitCode = `$LASTEXITCODE

"@
    } else {
        $script += @"
    # User scope: Use Add-AppxPackage for current user
    Add-AppxPackage -Path `$PackagePath
    `$ExitCode = `$LASTEXITCODE

"@
    }

    $script += @"
    if (`$null -eq `$ExitCode) { `$ExitCode = 0 }

    Write-Host "Installation completed with exit code: `$ExitCode"

    # Success codes
    `$SuccessCodes = @(0)

    if (`$ExitCode -in `$SuccessCodes) {
        Write-Host "Installation successful!"
        Stop-Transcript
        exit 0
    }
    else {
        throw "Installation failed with exit code: `$ExitCode"
    }
}
catch {
    Write-Error "Installation failed: `$_"
    Stop-Transcript
    exit 1
}
"@

    return $script
}
