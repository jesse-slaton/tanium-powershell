function New-MsixRemoveScript {
    <#
    .SYNOPSIS
        Generates removal script for MSIX/AppX packages.

    .DESCRIPTION
        Creates PowerShell removal scripts for msstore packages with proper
        Remove-AppxPackage commands and dependency handling.

    .PARAMETER PackageName
        Display name of the main package

    .PARAMETER PackageId
        Package ID (Store Product ID)

    .PARAMETER PackageFamilyName
        Package family name (if known)

    .PARAMETER Scope
        Installation scope (user or machine)

    .PARAMETER AllInOne
        If true, includes dependency removal. If false, main package only.

    .EXAMPLE
        New-MsixRemoveScript -PackageName "Windows Notepad" -PackageId "9MSMLRH6LZF3" `
            -Scope "user" -AllInOne $true

    .OUTPUTS
        String containing the PowerShell removal script
    #>
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]
        [string]$PackageName,

        [Parameter(Mandatory)]
        [string]$PackageId,

        [Parameter()]
        [string]$PackageFamilyName,

        [Parameter()]
        [ValidateSet('user', 'machine')]
        [string]$Scope = 'user',

        [Parameter()]
        [bool]$AllInOne = $true
    )

    $sanitizedName = $PackageName -replace '[\\/:*?"<>|]', '_'
    $logBaseName = $PackageId -replace '[\\/:*?"<>|]', '_'

    $script = @"
<#
.SYNOPSIS
    Remove $PackageName via Tanium Deploy

.DESCRIPTION
    This script uninstalls the MSIX/AppX package: $PackageName
    Package ID: $PackageId
    Scope: $Scope

.NOTES
    Generated by Get-WinGetPackage.ps1
#>

[CmdletBinding()]
param()

`$ErrorActionPreference = 'Stop'

# Set up logging
`$LogPath = Join-Path `$env:TEMP "Remove-$logBaseName.log"
Start-Transcript -Path `$LogPath -Append

try {
    Write-Host "Removing $PackageName..."
    Write-Host "Package ID: $PackageId"
    Write-Host "Scope: $Scope"

    # Find installed package
"@

    if ($PackageFamilyName) {
        $script += @"
    `$InstalledPackage = Get-AppxPackage -Name "$PackageFamilyName" -ErrorAction SilentlyContinue

"@
    } else {
        $script += @"
    `$InstalledPackage = Get-AppxPackage -Name "*$PackageId*" -ErrorAction SilentlyContinue

"@
    }

    $script += @"
    if (-not `$InstalledPackage) {
        Write-Host "Package not found - may already be uninstalled"
        Stop-Transcript
        exit 0
    }

    Write-Host "Found: `$(`$InstalledPackage.PackageFullName)"
    Write-Host "Version: `$(`$InstalledPackage.Version)"

    # Remove the package
"@

    if ($Scope -eq 'machine') {
        $script += @"
    # Machine scope: Remove provisioned package
    Write-Host "Removing provisioned package..."
    try {
        Remove-AppxProvisionedPackage -Online -PackageName `$InstalledPackage.PackageFullName -ErrorAction SilentlyContinue | Out-Null
    }
    catch {
        Write-Warning "Could not remove provisioned package: $_"
    }

"@
    }

    $script += @"
    # Remove user package
    Write-Host "Removing installed package..."
    Remove-AppxPackage -Package `$InstalledPackage.PackageFullName
    `$ExitCode = `$LASTEXITCODE

    if (`$null -eq `$ExitCode) { `$ExitCode = 0 }

    Write-Host "Removal completed with exit code: `$ExitCode"

    # Success codes
    `$SuccessCodes = @(0)

    if (`$ExitCode -in `$SuccessCodes) {
        Write-Host "Removal successful!"
        Stop-Transcript
        exit 0
    }
    else {
        throw "Removal failed with exit code: `$ExitCode"
    }
}
catch {
    Write-Error "Removal failed: `$_"
    Stop-Transcript
    exit 1
}
"@

    return $script
}
