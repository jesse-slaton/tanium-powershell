function New-RemoveScript {
    [CmdletBinding(DefaultParameterSetName = 'WindowsUpdate')]
    param(
        # Windows Update specific parameters
        [Parameter(Mandatory, ParameterSetName = 'WindowsUpdate')]
        [string]$KB,

        [Parameter(Mandatory, ParameterSetName = 'WindowsUpdate')]
        [string]$KBNumber,

        [Parameter(Mandatory, ParameterSetName = 'WindowsUpdate')]
        [string]$Title,

        [Parameter(Mandatory, ParameterSetName = 'WindowsUpdate')]
        [string]$Classification,

        [Parameter(Mandatory, ParameterSetName = 'WindowsUpdate')]
        [string]$Products,

        # Generic parameters for any package type
        [Parameter(Mandatory, ParameterSetName = 'Generic')]
        [string]$ProductName,

        [Parameter(Mandatory, ParameterSetName = 'Generic')]
        [string]$ProductId,

        [Parameter(Mandatory, ParameterSetName = 'Generic')]
        [string]$ProductVersion,

        [Parameter(ParameterSetName = 'Generic')]
        [ValidateSet('winget', 'registry', 'wusa', 'dism', 'msiexec', 'custom')]
        [string]$UninstallMethod = 'winget',

        [Parameter(ParameterSetName = 'Generic')]
        [string]$UninstallCommand,

        [Parameter(ParameterSetName = 'Generic')]
        [string]$UninstallSwitches,

        [Parameter(ParameterSetName = 'Generic')]
        [int[]]$SuccessCodes = @(0, 3010, 1605),

        [Parameter(ParameterSetName = 'Generic')]
        [string]$AdditionalNotes
    )

    # Handle Windows Update parameter set
    if ($PSCmdlet.ParameterSetName -eq 'WindowsUpdate') {
        $ProductName = $Title
        $ProductId = $KB
        $ProductVersion = $KB
        $UninstallMethod = 'wusa'
        $AdditionalNotes = "KB: $KB`nClassification: $Classification`nProducts: $Products`nGenerated by Get-UpdateCatalogPackage.ps1"
        $SuccessCodes = @(0, 3010, 2359303)
    }

    # Build remove script using generic parameters
    $logBaseName = $ProductId -replace '[\\/:*?"<>|]', '_'
    $successCodesStr = ($SuccessCodes | ForEach-Object { $_.ToString() }) -join ', '

    $script = @"
<#
.SYNOPSIS
    Remove $ProductName via Tanium Deploy

.DESCRIPTION
    This script uninstalls $ProductName version $ProductVersion

    Product ID: $ProductId
"@

    if ($AdditionalNotes) {
        $script += "`n    $($AdditionalNotes -replace "`n", "`n    ")"
    }

    $script += @"

#>

[CmdletBinding()]
param()

`$ErrorActionPreference = 'Stop'

# Set up logging
`$LogPath = Join-Path `$env:TEMP "Remove-$logBaseName.log"
Start-Transcript -Path `$LogPath -Append

try {
    Write-Host "Removing $ProductName $ProductVersion..."
    Write-Host "Product ID: $ProductId"
    Write-Host "Uninstall Method: $UninstallMethod"

"@

    # Add uninstallation logic based on method
    switch ($UninstallMethod) {
        'winget' {
            # For WinGet packages, use registry-based uninstall
            $script += @"
    # Find uninstall string from registry
    `$UninstallPaths = @(
        'HKLM:\SOFTWARE\Microsoft\Windows\CurrentVersion\Uninstall\*'
        'HKLM:\SOFTWARE\WOW6432Node\Microsoft\Windows\CurrentVersion\Uninstall\*'
        'HKCU:\SOFTWARE\Microsoft\Windows\CurrentVersion\Uninstall\*'
    )

    `$UninstallInfo = Get-ItemProperty `$UninstallPaths -ErrorAction SilentlyContinue |
        Where-Object { `$_.DisplayName -like "*$ProductName*" } |
        Select-Object -First 1

    if (`$UninstallInfo) {
        Write-Host "Found installed application: `$(`$UninstallInfo.DisplayName)"

        if (`$UninstallInfo.UninstallString) {
            Write-Host "Uninstall string: `$(`$UninstallInfo.UninstallString)"

            # Parse uninstall command
            if (`$UninstallInfo.UninstallString -match 'MsiExec\.exe.*\{(.+?)\}') {
                # MSI-based uninstall
                `$ProductCode = `$matches[1]
                Write-Host "Using MSI uninstall for ProductCode: {`$ProductCode}"
                `$Process = Start-Process -FilePath 'msiexec.exe' -ArgumentList "/x {`$ProductCode} /qn /norestart" -Wait -PassThru -NoNewWindow
                `$ExitCode = `$Process.ExitCode
            } else {
                # Execute uninstall string directly
                `$UninstallCmd = `$UninstallInfo.UninstallString
                if (`$UninstallInfo.QuietUninstallString) {
                    `$UninstallCmd = `$UninstallInfo.QuietUninstallString
                }

                Write-Host "Running: `$UninstallCmd"
                `$Process = Start-Process -FilePath 'cmd.exe' -ArgumentList "/c `$UninstallCmd" -Wait -PassThru -NoNewWindow
                `$ExitCode = `$Process.ExitCode
            }
        } else {
            Write-Warning "No uninstall string found for $ProductName"
            Stop-Transcript
            exit 0
        }
    } else {
        Write-Warning "Application not found - may already be uninstalled"
        Stop-Transcript
        exit 0
    }

"@
        }

        'wusa' {
            $script += @"
    `$KBNumber = "$KBNumber"

    # Try to find the installed update
    Write-Host "Searching for installed update KB`$KBNumber..."

    # Method 1: Try Get-HotFix
    `$HotFix = Get-HotFix -Id "KB`$KBNumber" -ErrorAction SilentlyContinue

    if (`$HotFix) {
        Write-Host "Found update via Get-HotFix"

        `$Arguments = @(
            '/uninstall'
            "/kb:`$KBNumber"
            '/quiet'
            '/norestart'
        )

        `$Process = Start-Process -FilePath 'wusa.exe' -ArgumentList `$Arguments -Wait -PassThru -NoNewWindow
        `$ExitCode = `$Process.ExitCode
    }
    else {
        # Method 2: Try DISM
        Write-Host "Attempting removal via DISM..."

        `$Packages = dism /online /get-packages | Select-String "Package Identity" | ForEach-Object {
            `$_.ToString().Replace("Package Identity : ", "").Trim()
        }

        `$TargetPackage = `$Packages | Where-Object { `$_ -match "KB`$KBNumber" } | Select-Object -First 1

        if (`$TargetPackage) {
            Write-Host "Found package: `$TargetPackage"

            `$Arguments = @(
                '/Online'
                '/Remove-Package'
                "/PackageName:`$TargetPackage"
                '/Quiet'
                '/NoRestart'
            )

            `$Process = Start-Process -FilePath 'dism.exe' -ArgumentList `$Arguments -Wait -PassThru -NoNewWindow
            `$ExitCode = `$Process.ExitCode
        }
        else {
            Write-Warning "Update KB`$KBNumber not found - may already be uninstalled"
            Stop-Transcript
            exit 0
        }
    }

"@
        }

        'custom' {
            if ($UninstallCommand) {
                $script += @"
    # Custom uninstall command
    Write-Host "Running: $UninstallCommand $UninstallSwitches"
    `$Process = Start-Process -FilePath '$UninstallCommand' -ArgumentList '$UninstallSwitches' -Wait -PassThru -NoNewWindow
    `$ExitCode = `$Process.ExitCode

"@
            }
        }

        default {
            # Default to registry-based uninstall (same as 'winget' method)
            $script += @"
    # Find uninstall string from registry
    `$UninstallPaths = @(
        'HKLM:\SOFTWARE\Microsoft\Windows\CurrentVersion\Uninstall\*'
        'HKLM:\SOFTWARE\WOW6432Node\Microsoft\Windows\CurrentVersion\Uninstall\*'
        'HKCU:\SOFTWARE\Microsoft\Windows\CurrentVersion\Uninstall\*'
    )

    `$UninstallInfo = Get-ItemProperty `$UninstallPaths -ErrorAction SilentlyContinue |
        Where-Object { `$_.DisplayName -like "*$ProductName*" } |
        Select-Object -First 1

    if (`$UninstallInfo -and `$UninstallInfo.UninstallString) {
        Write-Host "Found: `$(`$UninstallInfo.DisplayName)"
        Write-Host "Running: `$(`$UninstallInfo.UninstallString)"
        `$Process = Start-Process -FilePath 'cmd.exe' -ArgumentList "/c `$(`$UninstallInfo.UninstallString)" -Wait -PassThru -NoNewWindow
        `$ExitCode = `$Process.ExitCode
    } else {
        Write-Warning "Application not found - may already be uninstalled"
        Stop-Transcript
        exit 0
    }

"@
        }
    }

    $script += @"
    Write-Host "Removal completed with exit code: `$ExitCode"

    # Success codes
    `$SuccessCodes = @($successCodesStr)

    if (`$ExitCode -in `$SuccessCodes) {
        Write-Host "Removal successful!"

        if (`$ExitCode -eq 3010 -or `$ExitCode -eq 1641) {
            Write-Warning "A restart is required to complete the removal."
        }

        Stop-Transcript
        exit 0
    }
    elseif (`$ExitCode -eq 1605) {
        Write-Host "Package not found - may already be uninstalled"
        Stop-Transcript
        exit 0
    }
    else {
        throw "Removal failed with exit code: `$ExitCode"
    }
}
catch {
    Write-Error "Removal failed: `$_"
    Stop-Transcript
    exit 1
}
"@

    return $script
}
