function New-InstallScript {
    [CmdletBinding(DefaultParameterSetName = 'WindowsUpdate')]
    param(
        # Windows Update specific parameters
        [Parameter(Mandatory, ParameterSetName = 'WindowsUpdate')]
        [System.IO.FileInfo]$UpdateFile,

        [Parameter(Mandatory, ParameterSetName = 'WindowsUpdate')]
        [string]$KB,

        [Parameter(Mandatory, ParameterSetName = 'WindowsUpdate')]
        [string]$Title,

        [Parameter(Mandatory, ParameterSetName = 'WindowsUpdate')]
        [string]$Classification,

        [Parameter(Mandatory, ParameterSetName = 'WindowsUpdate')]
        [string]$Products,

        # Generic parameters for any package type
        [Parameter(Mandatory, ParameterSetName = 'Generic')]
        [string]$ProductName,

        [Parameter(Mandatory, ParameterSetName = 'Generic')]
        [string]$ProductId,

        [Parameter(Mandatory, ParameterSetName = 'Generic')]
        [string]$ProductVersion,

        [Parameter(ParameterSetName = 'Generic')]
        [string]$InstallerFile,

        [Parameter(ParameterSetName = 'Generic')]
        [string]$InstallerType,

        [Parameter(ParameterSetName = 'Generic')]
        [string]$InstallCommand,

        [Parameter(ParameterSetName = 'Generic')]
        [string]$InstallSwitches,

        [Parameter(ParameterSetName = 'Generic')]
        [int[]]$SuccessCodes = @(0, 3010),

        [Parameter(ParameterSetName = 'Generic')]
        [int]$Timeout = 1800,

        [Parameter(ParameterSetName = 'Generic')]
        [ValidateSet('user', 'machine', 'both')]
        [string]$Scope = 'machine',

        [Parameter(ParameterSetName = 'Generic')]
        [string]$AdditionalNotes
    )

    # Handle Windows Update parameter set
    if ($PSCmdlet.ParameterSetName -eq 'WindowsUpdate') {
        $ProductName = $Title
        $ProductId = $KB
        $ProductVersion = $KB
        $InstallerFile = $UpdateFile.Name
        $InstallerType = $UpdateFile.Extension.ToLower().TrimStart('.')
        $AdditionalNotes = "KB: $KB`nClassification: $Classification`nProducts: $Products`nGenerated by Get-UpdateCatalogPackage.ps1"

        # Set install parameters based on file type
        switch ($UpdateFile.Extension.ToLower()) {
            '.msu' {
                $InstallCommand = 'wusa.exe'
                $InstallSwitches = '/quiet /norestart'
                $SuccessCodes = @(0, 3010, 2359302)
            }
            '.cab' {
                $InstallCommand = 'dism.exe'
                $InstallSwitches = '/Online /Add-Package /Quiet /NoRestart'
                $SuccessCodes = @(0, 3010)
            }
            '.exe' {
                $InstallCommand = '$InstallerPath'
                $InstallSwitches = '/quiet /norestart'
                $SuccessCodes = @(0, 3010)
            }
        }
    }

    # Build install script using generic parameters
    $logBaseName = $ProductId -replace '[\\/:*?"<>|]', '_'
    $successCodesStr = ($SuccessCodes | ForEach-Object { $_.ToString() }) -join ', '

    $script = @"
<#
.SYNOPSIS
    Install $ProductName via Tanium Deploy

.DESCRIPTION
    This script installs $ProductName version $ProductVersion

    Product ID: $ProductId
"@

    if ($AdditionalNotes) {
        $script += "`n    $($AdditionalNotes -replace "`n", "`n    ")"
    }

    $script += @"

#>

[CmdletBinding()]
param()

`$ErrorActionPreference = 'Stop'

# Set up logging
`$LogPath = Join-Path `$env:TEMP "Install-$logBaseName.log"
Start-Transcript -Path `$LogPath -Append

try {
    Write-Host "Installing $ProductName $ProductVersion..."
    Write-Host "Product ID: $ProductId"
"@

    if ($InstallerType) {
        $script += "`n    Write-Host `"Installer Type: $InstallerType`""
    }

    # Check if installer file is required
    if (-not $InstallerFile) {
        # No installer file provided - script will fail
        $script += @"

    throw "No installer file found in package. This package must be rebuilt with -DownloadInstallers flag or Tanium Server must download the installer first."

"@
    } else {
        # Installer file provided - normal installation flow
        $script += @"


    # Get the installer file path
    `$InstallerPath = Join-Path `$PSScriptRoot "$InstallerFile"

    if (-not (Test-Path `$InstallerPath)) {
        throw "Installer file not found: `$InstallerPath"
    }

    Write-Host "Installer file: `$InstallerPath"
    Write-Host "File size: `$((Get-Item `$InstallerPath).Length / 1MB) MB"

"@

    # Add installation command
    if ($InstallCommand) {
        # Custom install command provided
        $cmdToExecute = $InstallCommand -replace '\{InstallerPath\}', '$InstallerPath'

        if ($cmdToExecute -match '^\$') {
            # Command is a variable (like $InstallerPath)
            $script += @"
    # Execute installation
    Write-Host "Running: `$InstallerPath $InstallSwitches"
    `$Process = Start-Process -FilePath `$InstallerPath -ArgumentList '$InstallSwitches' -Wait -PassThru -NoNewWindow
    `$ExitCode = `$Process.ExitCode

"@
        } elseif ($cmdToExecute -match 'Add-AppxPackage') {
            # PowerShell command for AppX
            $script += @"
    # Execute installation
    Write-Host "Running: Add-AppxPackage -Path `$InstallerPath"
    Add-AppxPackage -Path `$InstallerPath
    `$ExitCode = `$LASTEXITCODE

"@
        } else {
            # External command like msiexec.exe, wusa.exe, dism.exe
            $script += @"
    # Execute installation
    Write-Host "Running: $cmdToExecute $InstallSwitches"
    `$Process = Start-Process -FilePath '$cmdToExecute' -ArgumentList '$InstallSwitches' -Wait -PassThru -NoNewWindow
    `$ExitCode = `$Process.ExitCode

"@
        }
        } else {
            # Fallback: try to run installer directly
            $script += @"
    # Execute installation
    Write-Host "Running: `$InstallerPath $InstallSwitches"
    `$Process = Start-Process -FilePath `$InstallerPath -ArgumentList '$InstallSwitches' -Wait -PassThru -NoNewWindow
    `$ExitCode = `$Process.ExitCode

"@
        }
    }

    $script += @"
    Write-Host "Installation completed with exit code: `$ExitCode"

    # Success codes
    `$SuccessCodes = @($successCodesStr)

    if (`$ExitCode -in `$SuccessCodes) {
        Write-Host "Installation successful!"

        if (`$ExitCode -eq 3010 -or `$ExitCode -eq 1641) {
            Write-Warning "A restart is required to complete the installation."
        }

        Stop-Transcript
        exit 0
    }
    else {
        throw "Installation failed with exit code: `$ExitCode"
    }
}
catch {
    Write-Error "Installation failed: `$_"
    Stop-Transcript
    exit 1
}
"@

    return $script
}
